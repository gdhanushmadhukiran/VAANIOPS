@pytest.fixture
def generate_wav():
    """
    Generates genuine in-memory mono PCM 16-bit WAV bytes with specified duration.
    """
    def _create(duration_seconds: float = 1.0, sample_rate: int = 16000) -> bytes:
        buffer = io.BytesIO()
        num_samples = int(duration_seconds * sample_rate)
        with wave.open(buffer, "wb") as wav_file:
            wav_file.setnchannels(1)  # Mono
            wav_file.setsampwidth(2)  # 16-bit PCM
            wav_file.setframerate(sample_rate)
            # Write silence (zeros)
            raw_frames = struct.pack(f"<{num_samples}h", *([0] * num_samples))
            wav_file.writeframes(raw_frames)
        return buffer.getvalue()

    return _create

